namespace JeffreyBostoenExtensions\MailToTicket\Steps;

use JeffreyBostoenExtensions\MailToTicket\{
	ProcessingHelper
};

use RawEmailMessage;


/**
 * Class AutoReply.  
 * A policy to handle auto-reply e-mails.
 */
abstract class AutoReply extends Base {
	
	/**
	 * @inheritDoc
	 */
	public static int $iPrecedence = 10;
	
	/**
	 * @inheritDoc
	 */
	public static string $sXMLSettingsPrefix = 'policy_autoreply';
		
	/**
	 * @inheritDoc
	 */
	public static function Execute() : void {
		
		if(static::IsAutoGenerated(ProcessingHelper::GetRawMail())) {

			static::Trace('.. The message is an auto-reply.');
			static::HandleViolation();

		}

	}

	/**
	 * Whether the message was generated automatically (e.g. an out-of-office reply), based on its headers.
	 *
	 * @param RawEmailMessage $oRawEmail Raw e-mail message.
	 *
	 * @return bool
	 */
	public static function IsAutoGenerated(RawEmailMessage $oRawEmail) : bool {

		// https://www.iana.org/assignments/auto-submitted-keywords/auto-submitted-keywords.xhtml
		// Values for auto-submitted: no, auto-generated, auto-replied, auto-notified
		return (string)$oRawEmail->GetHeader('x-autoreply') !== ''
			|| (string)$oRawEmail->GetHeader('x-autorespond') !== ''
			|| strtolower((string)$oRawEmail->GetHeader('precedence')) === 'auto_reply'
			|| preg_match('/^auto/', strtolower((string)$oRawEmail->GetHeader('auto-submitted'))) === 1;

	}
	
}
